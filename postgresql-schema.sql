
-- PostgreSQL schema for Product Inventory Management
-- This file is separate from the application's default H2 database.

CREATE TABLE IF NOT EXISTS categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    description VARCHAR(500)
);

CREATE TABLE IF NOT EXISTS products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    description VARCHAR(1000),
    price NUMERIC(12, 2) NOT NULL,
    quantity INTEGER NOT NULL,
    primary_category_id BIGINT,

    CONSTRAINT fk_products_primary_category
        FOREIGN KEY (primary_category_id)
        REFERENCES categories(id)
);

CREATE TABLE IF NOT EXISTS product_categories (
    product_id BIGINT NOT NULL,
    category_id BIGINT NOT NULL,

    PRIMARY KEY (product_id, category_id),

    CONSTRAINT fk_product_categories_product
        FOREIGN KEY (product_id)
        REFERENCES products(id),

    CONSTRAINT fk_product_categories_category
        FOREIGN KEY (category_id)
        REFERENCES categories(id)
);

-- Optional indexes for foreign-key lookups.
CREATE INDEX IF NOT EXISTS idx_products_primary_category
    ON products(primary_category_id);

CREATE INDEX IF NOT EXISTS idx_product_categories_category
    ON product_categories(category_id);
